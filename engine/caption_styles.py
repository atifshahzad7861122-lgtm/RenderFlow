def rgb_to_ass_color(hex_str: str, alpha: int = 0) -> str:
    """
    Convert '#RRGGBB' or 'RRGGBB' with 0-255 alpha (0=opaque, 255=transparent)
    to ASS format '&HAABBGGRR&'.
    """
    clean = hex_str.strip().lstrip("#")
    if len(clean) == 3:
        clean = "".join([c * 2 for c in clean])
    if len(clean) != 6:
        clean = "FFFFFF"
    r = clean[0:2]
    g = clean[2:4]
    b = clean[4:6]
    a = f"{alpha:02X}"
    return f"&H{a}{b}{g}{r}&"


