DEFAULT_STYLE_KEY = "classic"


def get_all_styles() -> Dict[str, Dict[str, Any]]:
    """Return all caption style definitions."""
    return CAPTION_STYLES


def get_style(style_name: Optional[str]) -> Dict[str, Any]:
    """Retrieve style configuration with fallback to 'classic'."""
    if not style_name:
        return CAPTION_STYLES[DEFAULT_STYLE_KEY]
    clean = style_name.strip().lower()
    return CAPTION_STYLES.get(clean, CAPTION_STYLES[DEFAULT_STYLE_KEY])


def get_styles_by_category(category_id: str) -> List[Dict[str, Any]]:
    """Retrieve all styles belonging to a specific category."""
    cat_clean = (category_id or "all").strip().lower()
    if cat_clean == "all":
        return list(CAPTION_STYLES.values())
    return [s for s in CAPTION_STYLES.values() if s.get("category") == cat_clean]


def search_styles(query: str) -> List[Dict[str, Any]]:
    """Search styles by name or description."""
    q = (query or "").strip().lower()
    if not q:
        return list(CAPTION_STYLES.values())
    return [
        s for s in CAPTION_STYLES.values()
        if q in s.get("name", "").lower() or q in s.get("description", "").lower() or q in s.get("id", "").lower()
    ]


def resolve_auto_style(content_mode: Optional[str] = None) -> str:
    """Deterministic style resolution for 'auto' mode."""
    if not content_mode:
        return "classic"
    m = content_mode.lower()
    # Creator / Social matches
    if any(k in m for k in ["hormozi", "business", "sales", "finance"]):
        return "hormozi"
    elif any(k in m for k in ["beast", "challenge", "gaming", "fun"]):
        return "mrbeast"
    elif any(k in m for k in ["ali", "abdaal", "productivity", "study", "self_help"]):
        return "ali_abdaal"
    elif any(k in m for k in ["gadzhi", "luxury", "wealth"]):
        return "iman_gadzhi"
    elif any(k in m for k in ["tiktok", "short", "reel", "viral"]):
        return "bold_viral"
    elif any(k in m for k in ["podcast", "interview", "conversation"]):
        return "raj_shamani"
    elif any(k in m for k in ["mumbai", "desi", "hindi", "urdu", "bollywood"]):
        return "mumbai"
    elif any(k in m for k in ["doc", "history", "education", "lore", "story"]):
        return "classic"
    elif any(k in m for k in ["editorial", "cinema", "essay"]):
        return "editorial"
    elif any(k in m for k in ["music", "song", "karaoke"]):
        return "karaoke"
    elif any(k in m for k in ["minimal", "clean", "calm"]):
        return "minimal"
    return "classic"


def customize_style(
    base_style_key: str,
    overrides: Optional[Dict[str, Any]] = None,
    platform_preset: Optional[str] = None
) -> Dict[str, Any]:
    """
    Return a customized style dictionary based on user parameters and platform preset.
    """
    style = get_style(base_style_key).copy()

    # Apply platform preset adjustments first
    if platform_preset and platform_preset in PLATFORM_PRESETS:
        preset = PLATFORM_PRESETS[platform_preset]
        style["margin_v"] = preset["margin_v"]
        style["margin_lr"] = preset["margin_lr"]
        style["font_size"] = int(style["font_size"] * preset.get("font_scale", 1.0))
        style["max_width_chars"] = preset["max_width_chars"]

    if not overrides:
        return style

    # Direct allowed overrides
    for k in [
        "font", "font_size", "font_weight", "primary_color", "secondary_color",
        "highlight_color", "outline_color", "outline_width", "shadow_depth",
        "position", "word_highlight", "animation", "italic", "uppercase",
        "box_color", "box_alpha", "border_style", "margin_v", "margin_lr"
    ]:
        if k in overrides and overrides[k] is not None:
            style[k] = overrides[k]

    # Map position name to ASS alignment
    pos = str(style.get("position", "bottom")).lower()
    if pos == "top":
        style["alignment"] = 8  # Top-center
        if style.get("margin_v", 0) <= 0:
            style["margin_v"] = 65
    elif pos == "center":
        style["alignment"] = 5  # Mid-center
        style["margin_v"] = 0
    else:
        style["alignment"] = 2  # Bottom-center
        if style.get("margin_v", 0) <= 0:
            style["margin_v"] = 65

    return style
